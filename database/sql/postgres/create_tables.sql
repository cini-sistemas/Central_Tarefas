  PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "TIME_MEMBROS" (
  "id" SERIAL,
  "codigo" VARCHAR(20) NOT NULL,
  "nome" VARCHAR(200) NOT NULL,
  "grupo" VARCHAR(100) NULL,
  "data_cadastro" TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
