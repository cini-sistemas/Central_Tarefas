CREATE TABLE IF NOT EXISTS "ANOTACOES" (
  "id" SERIAL,
  "titulo" VARCHAR(300) NULL,
  "conteudo" TEXT NULL,
  "cor" VARCHAR(30) NOT NULL DEFAULT 'default',
  "fixado" BOOLEAN NOT NULL DEFAULT FALSE,
  "arquivado" BOOLEAN NOT NULL DEFAULT FALSE,
  "id_usuario" VARCHAR(200) NULL,
  "data_criacao" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "data_atualizacao" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "visibilidade" VARCHAR(10) NULL DEFAULT 'privado',
  "grupo_acesso" VARCHAR(100) NULL,
  PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "ETIQUETAS" (
  "id" SERIAL,
  "nome" VARCHAR(100) NOT NULL,
  "cor" VARCHAR(30) NOT NULL DEFAULT '#64748b',
  "data_criacao" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "ANOTACOES_ETIQUETAS" (
  "id_anotacao" INT NOT NULL,
  "id_etiqueta" INT NOT NULL,
  PRIMARY KEY ("id_anotacao", "id_etiqueta")
);

CREATE TABLE IF NOT EXISTS "CATEGORIAS" (
  "id" SERIAL,
  "nome" VARCHAR(100) NOT NULL,
  "cor" VARCHAR(30) NOT NULL DEFAULT '#1e40af',
  "icone" VARCHAR(50) NULL,
  "ativo" BOOLEAN NOT NULL DEFAULT TRUE,
  "data_criacao" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "TAREFAS" (
  "id" SERIAL,
  "titulo" VARCHAR(300) NOT NULL,
  "descricao" TEXT NULL,
  "status" VARCHAR(20) NOT NULL DEFAULT 'A_FAZER',
  "prioridade" VARCHAR(10) NOT NULL DEFAULT 'MEDIA',
